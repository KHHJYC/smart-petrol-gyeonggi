import assert from 'node:assert/strict';
import {gzipSync} from 'node:zlib';
import {build} from 'esbuild';
import vm from 'node:vm';
import fs from 'node:fs';
const result=await build({entryPoints:['html-preview/runtime.ts'],bundle:true,write:false,format:'iife',globalName:'PreviewRuntime',platform:'browser'});
const state=new Map();
const nativeFetch=async()=>{throw Error('Unexpected external request')};
const context=vm.createContext({window:{fetch:nativeFetch,location:{href:'file:///C:/preview/index.html'},DecompressionStream,__SMART_HTML_DATA__:{'data/test.json':gzipSync(' {"realData":true} ').toString('base64')}},localStorage:{getItem:k=>state.get(k)||null,setItem:(k,v)=>state.set(k,v)},Response,Request,URL,Blob,DecompressionStream,atob,crypto});
vm.runInContext(result.outputFiles[0].text,context);context.PreviewRuntime.installHtmlPreview();
const request=context.window.fetch;
assert.deepEqual(await (await request('/data/test.json')).json(),{realData:true});
assert.deepEqual(await (await request('/api/records')).json().then(b=>b.reports),[]);
const created=await request('/api/records',{method:'POST',body:JSON.stringify({kind:'report',title:'보안등 점검',description:'미리보기 테스트',lat:37.42,lng:127.12})});assert.equal(created.status,201);
const {id}=await created.json();assert.equal((await (await request('/api/records')).json()).reports[0].id,id);
assert.equal((await request('/api/records',{method:'PATCH',body:JSON.stringify({id,status:'조치 확인',evidence:''})})).status,400);
assert.equal((await request('/api/records',{method:'PATCH',body:JSON.stringify({id,status:'현장 확인',evidence:'현장 점등 관찰'})})).status,200);
const html=fs.readFileSync('../../outputs/스마트펫트롤_HTML/index.html','utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]);assert.equal(scripts.length,2);for(const script of scripts)new vm.Script(script);
assert.ok(!html.includes('<script src='));assert.ok(!html.includes('type="module"'));assert.ok(html.includes('서버 저장·API 자동 갱신 미연결'));
console.log('Passed: file URL dataset decoding, local preview save/read/evidence checks, inline JavaScript parsing, no external script dependency.');
